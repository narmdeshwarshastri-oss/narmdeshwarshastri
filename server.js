const express = require('express');
const http = require('http');
const path = require('path');
const fs = require('fs');
const { Server } = require('socket.io');

const app = express();
const server = http.createServer(app);
const io = new Server(server, {
  // Detect a dropped phone within ~20s instead of the default ~45s,
  // so the other side's "waiting" screen comes back sooner.
  pingInterval: 10000,
  pingTimeout: 10000,
  // Signaling messages are tiny; cap payloads so nobody can flood memory.
  maxHttpBufferSize: 1e5
});

const PORT = process.env.PORT || 3000;
// Optional: set PUBLIC_URL (e.g. https://call.example.com) so the
// WhatsApp/OG preview always points at the right domain.
const PUBLIC_URL = (process.env.PUBLIC_URL || '').replace(/\/+$/, '');
const PUBLIC_DIR = path.join(__dirname, 'public');
const ID_RE = /^[a-z0-9_-]{1,64}$/i;

app.disable('x-powered-by');
app.set('trust proxy', 1); // Render / Railway / Heroku sit behind a proxy

const indexTemplate = fs.readFileSync(path.join(PUBLIC_DIR, 'index.html'), 'utf8');

function renderIndex(req) {
  const origin = PUBLIC_URL || `${req.protocol}://${req.get('host')}`;
  return indexTemplate.replace(/__ORIGIN__/g, origin);
}

app.get(['/', '/index.html'], (req, res) => {
  res.set('Cache-Control', 'no-cache');
  res.type('html').send(renderIndex(req));
});

app.get('/healthz', (req, res) => {
  res.json({ ok: true, rooms: rooms.size, uptime: Math.round(process.uptime()) });
});

app.use(express.static(PUBLIC_DIR, {
  index: false,
  setHeaders(res, filePath) {
    // Images rarely change; JS/CSS must be re-validated so updates show up right away
    const cache = /\.(png|jpe?g|svg|ico|webp)$/i.test(filePath) ? 'public, max-age=86400' : 'no-cache';
    res.setHeader('Cache-Control', cache);
  }
}));

// roomId -> Map(peerId -> socketId)
// peerId is generated by the browser and survives reconnects, so a phone
// that switches from WiFi to 4G can come back into the same room and
// re-establish the call instead of being told the room is full.
const rooms = new Map();

// When a socket drops unexpectedly (WiFi -> 4G switch, phone screen off)
// keep its seat for a few seconds so the same peer can slip back in
// without the other side being told they left.
const LEAVE_GRACE_MS = 4000;
const pendingLeaves = new Map(); // "roomId:peerId" -> timeout

function removeFromRoom(roomId, peerId, socketId) {
  const room = rooms.get(roomId);
  if (!room || room.get(peerId) !== socketId) return; // seat already re-taken
  room.delete(peerId);
  if (room.size === 0) {
    rooms.delete(roomId);
  } else {
    io.to(roomId).emit('user-left', { socketId, peerId });
  }
}

function leaveRoom(socket, { graceful = false } = {}) {
  const { roomId, peerId } = socket;
  if (!roomId) return;
  socket.roomId = null;
  socket.peerId = null;
  socket.leave(roomId);

  const room = rooms.get(roomId);
  if (!room || room.get(peerId) !== socket.id) return; // a newer socket took over

  const key = roomId + ':' + peerId;
  clearTimeout(pendingLeaves.get(key));
  if (!graceful) {
    pendingLeaves.delete(key);
    removeFromRoom(roomId, peerId, socket.id);
    return;
  }
  pendingLeaves.set(key, setTimeout(() => {
    pendingLeaves.delete(key);
    removeFromRoom(roomId, peerId, socket.id);
  }, LEAVE_GRACE_MS));
}

io.on('connection', (socket) => {
  console.log('User connected:', socket.id);

  socket.on('join-room', (roomId, peerId, ack) => {
    if (typeof ack !== 'function') ack = () => {};
    if (typeof roomId !== 'string' || !ID_RE.test(roomId) ||
        typeof peerId !== 'string' || !ID_RE.test(peerId)) {
      return ack({ ok: false, error: 'invalid' });
    }
    roomId = roomId.toLowerCase();

    let room = rooms.get(roomId);
    if (!room) {
      room = new Map();
      rooms.set(roomId, room);
    }

    const isRejoin = room.has(peerId);
    if (!isRejoin && room.size >= 2) {
      return ack({ ok: false, error: 'full' });
    }

    if (socket.roomId && socket.roomId !== roomId) leaveRoom(socket);

    if (isRejoin) {
      const key = roomId + ':' + peerId;
      clearTimeout(pendingLeaves.get(key));
      pendingLeaves.delete(key);
      const oldSocketId = room.get(peerId);
      if (oldSocketId !== socket.id) {
        const old = io.sockets.sockets.get(oldSocketId);
        if (old) {
          old.roomId = null;
          old.peerId = null;
          old.leave(roomId);
          old.emit('kicked');
        }
      }
    }

    room.set(peerId, socket.id);
    socket.join(roomId);
    socket.roomId = roomId;
    socket.peerId = peerId;

    ack({ ok: true, rejoined: isRejoin, peers: room.size });

    const other = [...room.entries()].find(([pid]) => pid !== peerId);
    if (other) {
      const [otherPeerId, otherSocketId] = other;
      // The newcomer makes the offer; the one already inside waits for it.
      socket.emit('other-user', { socketId: otherSocketId, peerId: otherPeerId });
      io.to(otherSocketId).emit('user-joined', { socketId: socket.id, peerId });
    }
  });

  // Relay signaling only between the two sockets of the same room.
  const relay = (event) => {
    socket.on(event, (payload) => {
      if (!payload || typeof payload !== 'object') return;
      const target = io.sockets.sockets.get(payload.target);
      if (!target || !socket.roomId || target.roomId !== socket.roomId) return;
      const data = Object.assign({}, payload);
      delete data.target;
      data.from = socket.id;
      target.emit(event, data);
    });
  };
  ['offer', 'answer', 'ice-candidate', 'media-state'].forEach(relay);

  socket.on('leave-room', () => leaveRoom(socket));

  socket.on('disconnect', () => {
    leaveRoom(socket, { graceful: true });
    console.log('User disconnected:', socket.id);
  });
});

server.listen(PORT, () => {
  console.log(`Server running at http://localhost:${PORT}`);
});
